"""Generate wiki/index.md from page frontmatter. The ONLY producer of index.md.

Full vs stub is decided by `tags: [stub]`. Full entity pages list under their
type section as `[[Name]] — summary`; stubs list (name-only, grouped) under
`## Stubs`; sources list as `[[stem.md]] — summary`. Aborts loudly on any page
whose frontmatter fails to parse or on a name collision across types — it must
never silently drop a page the way hand-editing did.

The installed command prints the catalog. The legacy adapter owns explicit writes.
"""
from __future__ import annotations

from pathlib import Path

from glassgraph.config import ConfigError, ENTITY_TYPES, VaultConfig
from glassgraph.core import frontmatter

TYPES = [("companies", "Companies"), ("technologies", "Technologies"),
         ("products", "Products"), ("markets", "Markets"), ("themes", "Themes")]
STUB_LABELS = {"companies": "Company", "technologies": "Technology",
               "products": "Product", "markets": "Market", "themes": "Theme"}

BANNER = ("# 2brain Wiki — Index\n\n"
          "<!-- GENERATED by .tools/wikilib/gen_index.py — do NOT hand-edit. "
          "Regenerate after every ingest wave. -->\n")


class IndexError_(ConfigError):
    """A page could not be indexed (parse failure or name collision)."""


def _is_stub(meta: dict) -> bool:
    tags = meta.get("tags") or []
    if isinstance(tags, str):
        tags = [tags]
    return "stub" in tags


def _summary(meta: dict | None, page: Path) -> str:
    value = meta.get("summary") if meta else None
    if value is None:
        return ""
    if not isinstance(value, str):
        raise IndexError_(f"{page}: use a string summary")
    return value.strip()


def _tags(meta: dict, page: Path) -> str | list[str]:
    value = meta.get("tags")
    if value is None:
        return []
    if isinstance(value, str):
        return value
    if not isinstance(value, list) or any(not isinstance(tag, str) for tag in value):
        raise IndexError_(f"{page}: use string tags")
    return value


def generate(wiki_root: Path, *, config: VaultConfig | None = None) -> str:
    """Return the complete legacy catalog without changing any files.

    Pass config for contained, excluded, configured scans. Without config,
    preserve the legacy folder selection for existing writer integrations.
    """
    seen: dict[str, Path] = {}
    full: dict[str, list[tuple[str, str]]] = {d: [] for d, _ in TYPES}
    stubs: dict[str, list[str]] = {d: [] for d, _ in TYPES}

    for directory in config.entity_dirs if config else [d for d, _ in TYPES]:
        ddir = wiki_root / directory
        pages = config.markdown_files(ddir) if config else sorted(ddir.glob("*.md"))
        for page in pages:
            parsed = frontmatter.parse_file(page)
            if parsed.error:
                raise IndexError_(f"{page}: frontmatter parse error: {parsed.error}")
            if parsed.metadata is None:
                raise IndexError_(f"{page}: no frontmatter")
            if "merged" in _tags(parsed.metadata, page):
                continue
            d = directory.casefold()
            if d not in ENTITY_TYPES:
                declared_type = parsed.metadata.get("type")
                d = next((name for name, kind in ENTITY_TYPES.items() if kind == declared_type), None)
                if d is None:
                    raise IndexError_(f"{page}: declare a supported entity type in custom directories")
            if page.stem in seen:
                raise IndexError_(f"name collision: {page.stem} in {seen[page.stem]} and {page}")
            seen[page.stem] = page
            summary = _summary(parsed.metadata, page)
            if _is_stub(parsed.metadata):
                stubs[d].append(page.stem)
            else:
                full[d].append((page.stem, summary))

    sources: list[tuple[str, str]] = []
    sdir = wiki_root / "sources"
    pages = config.markdown_files(sdir) if config else sorted(sdir.glob("*.md"))
    for page in pages:
        parsed = frontmatter.parse_file(page)
        if parsed.error:
            raise IndexError_(f"{page}: frontmatter parse error: {parsed.error}")
        summary = _summary(parsed.metadata, page)
        sources.append((page.stem, summary))

    out = [BANNER]
    total_full = sum(len(full[d]) for d, _ in TYPES)
    total_stub = sum(len(stubs[d]) for d, _ in TYPES)
    out.append(f"Catalog: {total_full} full entity pages, {total_stub} stubs, "
               f"{len(sources)} sources. Generated from page frontmatter.\n\n---\n")

    for d, title in TYPES:
        out.append(f"\n## {title}\n")
        out.append(f"\n*{len(full[d])} full pages | {len(stubs[d])} stubs (see Stubs section).*\n")
        for stem, summary in full[d]:
            out.append(f"[[{stem}]] — {summary}" if summary else f"[[{stem}]]")

    out.append(f"\n## Sources\n\n*{len(sources)} source pages.*\n")
    for stem, summary in sources:
        out.append(f"- [[{stem}.md]] — {summary}" if summary else f"- [[{stem}.md]]")

    out.append("\n## Stubs\n\n*Pages needing expansion.*\n")
    for d, _ in TYPES:
        if stubs[d]:
            out.append(f"\n### {STUB_LABELS[d]} stubs ({len(stubs[d])})\n")
            out.append(", ".join(f"[[{s}]]" for s in stubs[d]))

    return "\n".join(out) + "\n"
